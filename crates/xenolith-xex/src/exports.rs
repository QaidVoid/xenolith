/// What an export is, as the catalogue records it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExportKind {
    /// Something to call.
    Function,
    /// Something to read, which a title imports as a pointer rather than code.
    Variable,
}

/// One entry point a library exports.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Export {
    /// What it is called.
    pub name: &'static str,
    /// Whether it is called or read.
    pub kind: ExportKind,
}

/// Returns what a library's ordinal names, if the catalogue has it.
///
/// The library is named as the container names it, so the extension is ignored
/// and the comparison is made without regard to case.
#[must_use]
pub fn export(library: &str, ordinal: u32) -> Option<Export> {
    let stem = library
        .rsplit_once('.')
        .map_or(library, |(stem, _)| stem)
        .to_ascii_lowercase();

    let table: &[(u32, &str, ExportKind)] = match stem.as_str() {
        "xboxkrnl" => XBOXKRNL,
        "xam" => XAM,
        _ => return None,
    };

    table
        .binary_search_by_key(&ordinal, |(at, _, _)| *at)
        .ok()
        .and_then(|at| table.get(at))
        .map(|(_, name, kind)| Export { name, kind: *kind })
}

